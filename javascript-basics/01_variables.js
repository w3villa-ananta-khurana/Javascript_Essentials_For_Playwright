// Variables
// A variable is a container used to store data.
// Think of a variable as a labeled box.
// You can keep something inside that box and use it whenever needed.

// Why do we need variables? : Instead of writing the same value again and again,
// we store it once and reuse it.

let name = "Ananta";
const country = "India";

console.log(name);
console.log(country);

// Changing let
name = "Rahul";
console.log(name);

// 2. const : Value cannot be changed after assignment. Used for fixed values.
